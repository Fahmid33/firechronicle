"""FireChronicle - Data Scientist to Backend B Inference Interface.

Deliverable for Member 4 (Backend B) to integrate FastAPI /api/v1/harmonized.
Implements the exact shared model response schema specified in the
FireChronicle Final Team Rulebook (Section 5, p. 6).

SCIENTIFIC STATUS:
DEMO / SYNTHETIC / NOT SCIENTIFICALLY VALIDATED
All predictions generated by this module use baseline multipliers fitted
on synthetic test fixtures. They do NOT represent real NASA observations.
"""

import os
from pathlib import Path
import re
from typing import Any, Dict, List, Optional, Union
import joblib

from ratio_baseline import predict_ratio

MODEL_VERSION = "ratio-baseline-v1.0-synthetic-demo"
CANONICAL_BLOCK_PATTERN = re.compile(r"^-?\d+_-?\d+$")
_CACHED_MODEL: Optional[Dict[str, Any]] = None


def _find_model_path(custom_path: Optional[Union[str, Path]] = None) -> Path:
    """Resolve model artifact path robustly across backend execution directories."""
    if custom_path:
        p = Path(custom_path)
        if p.exists():
            return p
        raise FileNotFoundError(f"Specified model path not found: {p}")

    # Check environment variable
    env_path = os.environ.get("FIRECHRONICLE_MODEL_PATH")
    if env_path and Path(env_path).exists():
        return Path(env_path)

    # Resolution relative to this script
    this_dir = Path(__file__).resolve().parent
    candidates = [
        this_dir / "model.joblib",
        this_dir / "artifacts" / "ratio_model.joblib",
        Path.cwd() / "model" / "model.joblib",
        Path.cwd() / "model" / "artifacts" / "ratio_model.joblib",
        Path.cwd() / "model.joblib",
    ]
    for cand in candidates:
        if cand.exists():
            return cand

    # Default fallback path
    return this_dir / "model.joblib"


def load_model(model_path: Optional[Union[str, Path]] = None) -> Dict[str, Any]:
    """Load and cache the serialized model artifact."""
    global _CACHED_MODEL
    resolved_path = _find_model_path(model_path)
    if _CACHED_MODEL is None or model_path is not None:
        if not resolved_path.exists():
            raise FileNotFoundError(
                f"Model artifact not found at {resolved_path}. Run export_model.py first."
            )
        _CACHED_MODEL = joblib.load(resolved_path)
    return _CACHED_MODEL


def predict_viirs_equivalent(
    record: Dict[str, Any],
    model: Optional[Dict[str, Any]] = None
) -> Dict[str, Any]:
    """Predict VIIRS S-NPP-equivalent hotspot detection count for a single 50 km block observation.

    Validates region, temporal period, and input features. Returns the canonical
    FireChronicle response dictionary with appropriate status flags.

    Parameters
    ----------
    record : dict
        Input dictionary containing:
        - region_id (str, required: must be 'BR-PA')
        - block_id (str, required: canonical 'bx_by' format)
        - year (int, required)
        - month (int, required: 1-12)
        - daynight (str, required: 'D' or 'N')
        - modis_count (int, optional/required for estimation)
        - coverage_status (str, optional: default 'unknown')
    model : dict, optional
        Preloaded model dictionary containing 'multiplier_k' and metadata.

    Returns
    -------
    dict
        Standardized response matching Rulebook Section 5 schema.
    """
    model_obj = model if model is not None else load_model()
    k = model_obj.get("multiplier_k", 3.20)
    version = model_obj.get("model_version", MODEL_VERSION)

    region_id = record.get("region_id")
    block_id = record.get("block_id")
    year = record.get("year")
    month = record.get("month")
    daynight = record.get("daynight")
    coverage_status = record.get("coverage_status", "unknown")

    # Base response template matching Rulebook Section 5 (p. 6)
    response: Dict[str, Any] = {
        "region_id": "BR-PA",
        "block_id": str(block_id) if block_id is not None else None,
        "year": int(year) if year is not None and str(year).isdigit() else year,
        "month": int(month) if month is not None and str(month).isdigit() else month,
        "daynight": str(daynight) if daynight is not None else None,
        "estimated_viirs_count": None,
        "value_type": "estimated",
        "prediction_status": "ok_preliminary",
        "coverage_status": str(coverage_status) if coverage_status else "unknown",
        "model_version": version,
        "measurement_unit": "VIIRS_S-NPP-equivalent_detection_count",
        "calibration_scale_km": 50,
    }

    # 1. Validate Region (Pará only: Rulebook Section 1, p. 2)
    if region_id != "BR-PA":
        response["region_id"] = region_id
        response["prediction_status"] = "unsupported_region"
        return response

    # 2. Validate Canonical Block ID (EPSG:6933 50km 'bx_by' format)
    # Note: Valid regex syntax confirms formatting contract only, not geographic Pará clipping proof.
    if block_id is None or not isinstance(block_id, str) or not CANONICAL_BLOCK_PATTERN.match(block_id.strip()):
        response["prediction_status"] = "missing_required_feature"
        return response

    # 3. Validate Month and Day/Night
    if response["month"] not in range(1, 13) or response["daynight"] not in ("D", "N"):
        response["prediction_status"] = "missing_required_feature"
        return response

    # 4. Validate Temporal Period (Aqua MODIS science era starts July 2002; Overlap 2012-2020)
    if year is None or not isinstance(response["year"], int):
        response["prediction_status"] = "missing_required_feature"
        return response

    # Aqua MODIS launched May 4, 2002; science record begins July 2002 (Rulebook Section 1 & 3: Mid-2002–2011).
    if response["year"] < 2002 or (response["year"] == 2002 and response["month"] < 7):
        response["prediction_status"] = "unsupported_period"
        return response

    if response["year"] > 2026:
        response["prediction_status"] = "out_of_training_range"
        return response

    # 5. Validate Coverage Evidence (Preserves null status, does not substitute zero)
    if str(coverage_status).lower() in ("insufficient", "insufficient_coverage"):
        response["prediction_status"] = "insufficient_coverage"
        return response

    # 6. Validate Required MODIS Count Feature
    if "modis_count" not in record or record["modis_count"] is None:
        response["prediction_status"] = "missing_required_feature"
        return response

    modis_count = record["modis_count"]

    # 6. Execute Mathematical Prediction
    try:
        raw_pred = predict_ratio(modis_count, k=k)
        response["estimated_viirs_count"] = round(float(raw_pred), 2)
        response["prediction_status"] = "ok_preliminary"
    except (ValueError, TypeError):
        response["estimated_viirs_count"] = None
        response["prediction_status"] = "model_error"

    return response


def predict_batch(
    records: List[Dict[str, Any]],
    model: Optional[Dict[str, Any]] = None
) -> List[Dict[str, Any]]:
    """Execute batch inference for multiple 50 km block observations."""
    model_obj = model if model is not None else load_model()
    return [predict_viirs_equivalent(rec, model=model_obj) for rec in records]
